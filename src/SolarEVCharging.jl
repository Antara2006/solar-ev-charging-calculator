
module SolarEVCharging

export calculate_energy_needed,
       calculate_panel_energy,
       calculate_panels_required,
       calculate_array_power,
       calculate_charging_time

# Energy required to charge the battery
function calculate_energy_needed(
    capacity_kwh,
    current_soc,
    target_soc
)
    capacity_kwh > 0 ||
        throw(ArgumentError("Battery capacity must be positive."))

    0 <= current_soc <= 100 ||
        throw(ArgumentError("Current charge must be between 0 and 100%."))

    0 <= target_soc <= 100 ||
        throw(ArgumentError("Target charge must be between 0 and 100%."))

    target_soc > current_soc ||
        throw(ArgumentError("Target charge must exceed current charge."))

    return capacity_kwh * (target_soc - current_soc) / 100
end

# Energy generated by one panel in a day
function calculate_panel_energy(
    panel_power_kw,
    sunlight_hours,
    efficiency
)
    panel_power_kw > 0 ||
        throw(ArgumentError("Panel power must be positive."))

    sunlight_hours > 0 ||
        throw(ArgumentError("Sunlight hours must be positive."))

    0 < efficiency <= 1 ||
        throw(ArgumentError("Efficiency must be greater than 0 and at most 1."))

    return panel_power_kw * sunlight_hours * efficiency
end

# Whole number of panels required to generate the energy
function calculate_panels_required(
    energy_needed_kwh,
    panel_energy_kwh
)
    energy_needed_kwh > 0 ||
        throw(ArgumentError("Required energy must be positive."))

    panel_energy_kwh > 0 ||
        throw(ArgumentError("Panel energy must be positive."))

    return ceil(Int, energy_needed_kwh / panel_energy_kwh)
end

# Rated and effective power of the entire array
function calculate_array_power(
    panel_count,
    panel_power_kw,
    efficiency
)
    panel_count >= 1 ||
        throw(ArgumentError("Panel count must be at least one."))

    panel_power_kw > 0 ||
        throw(ArgumentError("Panel power must be positive."))

    0 < efficiency <= 1 ||
        throw(ArgumentError("Efficiency must be greater than 0 and at most 1."))

    rated_power_kw = panel_count * panel_power_kw
    effective_power_kw = rated_power_kw * efficiency

    return (rated = rated_power_kw, effective = effective_power_kw)
end

# Idealized charging time at a constant effective power
function calculate_charging_time(
    energy_needed_kwh,
    effective_power_kw
)
    energy_needed_kwh > 0 ||
        throw(ArgumentError("Required energy must be positive."))

    effective_power_kw > 0 ||
        throw(ArgumentError("Effective power must be positive."))

    return energy_needed_kwh / effective_power_kw
end

end # module
